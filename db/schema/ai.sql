    KEY `idx_ai_business_config_model` (`model_id`),
    KEY `idx_ai_business_config_enabled` (`enabled`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI业务配置表';

CREATE TABLE IF NOT EXISTS `ai_prompt_template` (
