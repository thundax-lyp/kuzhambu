CREATE TABLE IF NOT EXISTS `ai_invocation_log` (
    `id` bigint NOT NULL AUTO_INCREMENT COMMENT 'AI调用日志数据库主键',
    `call_id` bigint NOT NULL COMMENT 'AI调用日志业务ID，对外关联候选结果、任务和业务trace',
    `batch_id` bigint DEFAULT NULL COMMENT '批量任务业务ID，对应ai_batch_job.id，单次调用为空',
    `scope` varchar(32) DEFAULT NULL COMMENT '调用来源业务域或运行范围',
    `capability` varchar(64) NOT NULL COMMENT '本次调用使用的AI业务能力',
    `content_type` varchar(32) DEFAULT NULL COMMENT '被处理业务内容类型',
    `content_id` bigint DEFAULT NULL COMMENT '被处理业务内容ID',
    `object_id` bigint DEFAULT NULL COMMENT '被处理内容下的细分对象ID',
    `service_id` bigint DEFAULT NULL COMMENT '发起调用的AI服务配置ID',
    `service_role` varchar(16) DEFAULT NULL COMMENT '发起调用的AI服务角色',
    `model_id` bigint DEFAULT NULL COMMENT '实际使用的AI模型配置ID',
    `model_name` varchar(255) DEFAULT NULL COMMENT '实际使用的AI模型名称快照',
    `prompt_version_id` bigint DEFAULT NULL COMMENT '实际使用的提示词版本ID',
    `request_id` varchar(128) DEFAULT NULL COMMENT '调用请求ID，用于幂等和排查',
    `trace_id` varchar(128) DEFAULT NULL COMMENT '调用链路追踪ID',
    `status` varchar(16) NOT NULL DEFAULT 'RUNNING' COMMENT '调用状态：RUNNING/SUCCEEDED/FAILED',
    `stream_used` tinyint(1) NOT NULL DEFAULT 0 COMMENT '本次调用是否使用流式输出',
    `stream_completed` tinyint(1) NOT NULL DEFAULT 0 COMMENT '流式调用是否收到完成事件',
    `fallback_used` tinyint(1) NOT NULL DEFAULT 0 COMMENT '本次调用是否使用降级路径',
    `latency_ms` int DEFAULT NULL COMMENT '调用耗时毫秒数',
    `input_tokens` int NOT NULL DEFAULT 0 COMMENT '输入token数量',
    `output_tokens` int NOT NULL DEFAULT 0 COMMENT '输出token数量',
    `cost_amount` decimal(18, 6) NOT NULL DEFAULT 0.000000 COMMENT '本次调用成本金额快照',
    `failure_stage` varchar(64) DEFAULT NULL COMMENT '失败发生阶段',
    `result_format` varchar(32) DEFAULT NULL COMMENT '结果格式，例如TEXT/JSON/ARTIFACT',
    `result_payload` longtext DEFAULT NULL COMMENT '调用最终结果内容或对象存储结果引用',
    `artifact_reference_json` json DEFAULT NULL COMMENT 'worker返回的原始 artifact 引用信息',
    `error_type` varchar(32) DEFAULT NULL COMMENT '失败类型',
    `error_message` varchar(1024) DEFAULT NULL COMMENT '失败说明',
    `warnings_json` json DEFAULT NULL COMMENT 'worker返回的非阻断告警',
    `requested_at` datetime(3) NOT NULL COMMENT '调用发起时间',
    `completed_at` datetime(3) DEFAULT NULL COMMENT '调用完成时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_ai_invocation_log_id` (`call_id`),
    KEY `idx_ai_invocation_log_batch` (`batch_id`, `status`),
    KEY `idx_ai_invocation_log_target` (`content_type`, `content_id`, `capability`),
    KEY `idx_ai_invocation_log_status` (`status`, `requested_at`),
    KEY `idx_ai_invocation_log_trace` (`trace_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI调用结构化日志表，记录每次worker调用的请求、模型、结果、成本和错误，用于审计、排查和报表';

CREATE TABLE IF NOT EXISTS `ai_candidate` (
    `id` bigint NOT NULL COMMENT 'AI候选结果业务ID，对外作为candidateId使用',
    `call_id` bigint DEFAULT NULL COMMENT '生成该候选结果的AI调用日志业务ID，对应ai_invocation_log.call_id',
    `batch_id` bigint DEFAULT NULL COMMENT '批量任务业务ID，对应ai_batch_job.id，单次候选为空',
    `capability` varchar(64) NOT NULL COMMENT '生成该候选结果使用的AI业务能力',
    `content_type` varchar(32) NOT NULL COMMENT '候选结果所属业务内容类型',
    `content_id` bigint NOT NULL COMMENT '候选结果所属业务内容ID',
    `object_id` bigint DEFAULT NULL COMMENT '候选结果所属内容下的细分目标对象ID',
    `result_format` varchar(32) NOT NULL COMMENT '候选结果格式，例如TEXT/JSON/ARTIFACT',
    `result_payload` longtext DEFAULT NULL COMMENT '候选结果内容或对象存储结果引用',
    `status` varchar(16) NOT NULL DEFAULT 'PENDING' COMMENT '候选结果状态：PENDING/APPLIED/REJECTED',
    `artifact_reference_json` json DEFAULT NULL COMMENT 'worker返回的原始 artifact 引用信息',
    `failure_stage` varchar(64) DEFAULT NULL COMMENT '候选生成失败发生阶段',
    `prompt_version_id` bigint DEFAULT NULL COMMENT '生成候选使用的提示词版本ID',
    `model_name` varchar(255) DEFAULT NULL COMMENT '生成候选使用的AI模型名称快照',
    `error_type` varchar(32) DEFAULT NULL COMMENT '候选生成或处理失败类型',
    `error_message` varchar(1024) DEFAULT NULL COMMENT '候选生成或处理失败说明',
    `requested_at` datetime(3) NOT NULL COMMENT '候选生成请求时间',
    `applied_at` datetime(3) DEFAULT NULL COMMENT '候选被应用到正式业务数据的时间',
    `rejected_at` datetime(3) DEFAULT NULL COMMENT '候选被拒绝的时间',
    PRIMARY KEY (`id`),
    KEY `idx_ai_candidate_target` (`content_type`, `content_id`, `capability`),
    KEY `idx_ai_candidate_batch` (`batch_id`, `status`),
    KEY `idx_ai_candidate_call` (`call_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI候选结果表';

