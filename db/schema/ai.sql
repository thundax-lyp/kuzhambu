    `prompt_template_id` bigint NOT NULL,
    `model_id` bigint NOT NULL,
    `default_params_json` json DEFAULT NULL,
    `enabled` tinyint(1) NOT NULL DEFAULT 1,
    `priority` int NOT NULL DEFAULT 0,
    `configured_at` datetime(3) NOT NULL,
    PRIMARY KEY (`id`),
